#!/usr/bin/env python3
"""DLL8 line + SR-latch phase regeneration, device-level SPICE.

Per phase k:
  Q_k SET by the rising edge of tap_k, RESET by the rising edge of tap_(k+4).
  With 8d = T, tap_(k+4) is tap_k + T/2, so Q_k high time = T/2 exactly; both
  edges are rising edges, so the tap tpHL/tpLH asymmetry cannot enter duty.

Edge pulses are generated by NAND(tap, delayed_tap) + inverter; the latch is a
cross-coupled NAND2 pair.  Identical cells on every phase, and every tap drives
the same load (next-element inv_4 + tap buf + regen input), so the set-path
delay is matched across k.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import dll8_pex2 as m

OUT = Path("/grid/adpll_gen/flow/characterization/dll8_pex2")
WORKDIR = Path("/tmp/opencode/dll8regen/decks")


def emit_top(corner: str, code: int, period: float, wire: bool = True,
             ncyc: int = 3) -> str:
    c = m.CORNERS[corner]
    bits = [(code >> b) & 1 for b in range(7)]
    s = [f"* dll8 regen corner={corner} code={code} period={period}",
         f".TEMP {c['temp']}",
         f'.LIB "{m.CORNER_MOS}" {c["mos"]}',
         f'.LIB "{m.CORNER_CAP}" moscap_tt',
         f'.inc "{m.MOSCAP_MOD}"',
         f'.inc "{m.CELLS}"',
         ".inc dll8_elem.sp",
         f".PARAM CMID={'0.96f' if wire else '0f'}",
         ".OPTIONS RELTOL=3e-3 ABSTOL=1e-12 VNTOL=1e-6 GMIN=1e-12 TRTOL=15 ITL4=30",
         f"vvdd VDD 0 DC={c['vdd']}", "vvss VSS 0 DC=0"]
    for b in range(7):
        s.append(f"vc{b} C{b} 0 DC={c['vdd'] if bits[b] else 0.0}")
    s.append(m.pwl_square(period, c["vdd"], ncyc))
    # 8-element line; same load on every tap
    for i in range(8):
        s.append(f"Xn{i} x{i} x{i+1} C0 C1 C2 C3 C4 C5 C6 VDD VSS DLL8_ELEM")
        if wire:
            s.append(f"Cwire{i} x{i+1} 0 0.960f")
        s.append(f"Xtb{i} tb{i} x{i+1} VDD VSS sg13g2_buf_1")
        s.append(f"Xnx{i} nx{i} x{i+1} VDD VSS sg13g2_inv_4")
    # SR regeneration, one per phase
    for k in range(8):
        tk = f"x{k+1}"
        tk4 = f"x{((k+4) % 8)+1}"
        nl = f"k{k}"
        # set pulse: spn = NAND(tk, tk_delayed) -> sn = ~spn (active-low set)
        s.append(f"Xsda_{nl} sda{nl} {tk} VDD VSS sg13g2_inv_1")
        s.append(f"Xsdb_{nl} sdb{nl} sda{nl} VDD VSS sg13g2_inv_1")
        s.append(f"Xspn_{nl} spn{nl} {tk} sdb{nl} VDD VSS sg13g2_nand2_1")
        s.append(f"Xsn_{nl} sn{nl} spn{nl} VDD VSS sg13g2_inv_1")
        # reset pulse from tap_(k+4)
        s.append(f"Xrda_{nl} rda{nl} {tk4} VDD VSS sg13g2_inv_1")
        s.append(f"Xrdb_{nl} rdb{nl} rda{nl} VDD VSS sg13g2_inv_1")
        s.append(f"Xrpn_{nl} rpn{nl} {tk4} rdb{nl} VDD VSS sg13g2_nand2_1")
        s.append(f"Xrn_{nl} rn{nl} rpn{nl} VDD VSS sg13g2_inv_1")
        # cross-coupled NAND latch
        s.append(f"Xq_{nl} q{k} qb{k} sn{nl} VDD VSS sg13g2_nand2_1")
        s.append(f"Xqb_{nl} qb{k} q{k} rn{nl} VDD VSS sg13g2_nand2_1")
        s.append(f".ic V(q{k})=0 V(qb{k})=1")
    vecs = " ".join(f"v(x{i})" for i in range(1, 9))
    qs = " ".join(f"v(q{i})" for i in range(8))
    s += [".control", "set filetype=ascii", "run",
          f"wrdata tran.out v(IN) {vecs} {qs}", "quit", ".endc",
          f".TRAN 2p {period*(ncyc+2):.4g}n", ".end"]
    return "\n".join(s)


def measure(corner, code, period, raw: Path) -> dict:
    c = m.CORNERS[corner]; vdd = c["vdd"]; thr = 0.5*vdd
    t, w = m.parse_wrdata(raw)
    # v0=IN, v1..v8=x1..x8, v9..v16=q0..q7
    P = period*1e-9
    settle, stop = 1.2*P, 2.6*P
    res = dict(corner=corner, code=code, period=period)
    taps = [w[f"v{i+1}"] for i in range(8)]
    qs = [w[f"v{9+i}"] for i in range(8)]
    # set-path delay: q_k rising - tap_k rising (first edge in window)
    setd = []
    for k in range(8):
        tr = m.interp_cross(t, taps[k], thr, True)
        qr = m.interp_cross(t, qs[k], thr, True)
        tr = [x for x in tr if x > settle]
        qr = [x for x in qr if x > settle]
        if tr and qr:
            # nearest q rise after the tap rise
            qq = next((x for x in qr if x >= tr[0]-0.2e-9), None)
            if qq is not None:
                setd.append((qq-tr[0])*1e12)
    res["set_delay_ps"] = setd
    if len(setd) == 8:
        res["set_spread_ps"] = max(setd)-min(setd)
    # duty of q7 and all q
    duties = []
    for k in range(8):
        hi = lo = 0.0; pt = pv = None
        for tt, vv in zip(t, qs[k]):
            if tt < settle or tt > stop:
                pt, pv = tt, vv; continue
            if pt is not None:
                dt = tt-pt
                if (pv+vv)*0.5 > thr: hi += dt
                else: lo += dt
            pt, pv = tt, vv
        duties.append(100.0*hi/(hi+lo) if hi+lo > 0 else None)
    res["q_duty_pct"] = duties
    # raw tap duty for comparison (q7/tap7)
    def duty_of(v):
        hi = lo = 0.0; pt = pv = None
        for tt, vv in zip(t, v):
            if tt < settle or tt > stop:
                pt, pv = tt, vv; continue
            if pt is not None:
                dt = tt-pt
                if (pv+vv)*0.5 > thr: hi += dt
                else: lo += dt
            pt, pv = tt, vv
        return 100.0*hi/(hi+lo) if hi+lo > 0 else None
    res["raw_tap7_duty"] = duty_of(taps[7])
    return res


def run(cfg):
    d = WORKDIR / (f"{cfg['corner']}_c{cfg['code']:03d}_p{cfg['period']:.2f}")
    d.mkdir(parents=True, exist_ok=True)
    (d / "dll8_elem.sp").write_text(m.emit_elem2(7, cfg["code"], "npstrong"))
    (d / "top.sp").write_text(emit_top(cfg["corner"], cfg["code"],
                                       cfg["period"]))
    (d / ".spiceinit").write_text(
        f"set num_threads=1\nosdi {m.OSDI.resolve()}\nosdi {m.OSDI_NQS.resolve()}\n")
    raw = d / "tran.out"
    if not raw.exists():
        subprocess.run(["ngspice", "-b", "top.sp"], cwd=d, check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return measure(cfg["corner"], cfg["code"], cfg["period"], raw)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--corners", default="ss,tt,ff")
    ap.add_argument("--code", type=int, default=96)
    ap.add_argument("--codes", default="")
    ap.add_argument("--period", type=float, default=4.0)
    ap.add_argument("--jobs", type=int, default=3)
    ap.add_argument("--out", default=str(OUT / "regen.json"))
    a = ap.parse_args()
    codes = [int(x) for x in a.codes.split(",")] if a.codes else [a.code]
    periods = [float(x) for x in str(a.period).split(",")]
    cfgs = []
    for i, c in enumerate(a.corners.split(",")):
        for j, code in enumerate(codes):
            per = periods[min(i, len(periods)-1)] if len(periods) == 1 else periods[i]
            cfgs.append(dict(corner=c, code=code, period=per))
    with ThreadPoolExecutor(a.jobs) as ex:
        res = list(ex.map(run, cfgs))
    json.dump(res, open(a.out, "w"), indent=1)
    for r in res:
        d = r.get("q_duty_pct") or []
        print(f"{r['corner']}: set={r.get('set_delay_ps')} spread={r.get('set_spread_ps')} "
              f"q_duty={[round(x,2) if x else None for x in d]} "
              f"raw_tap7={r.get('raw_tap7_duty')}")


if __name__ == "__main__":
    main()
