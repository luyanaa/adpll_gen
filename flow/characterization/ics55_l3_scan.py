#!/usr/bin/env python3
"""L3 ics55 DCO scan using flattened CDL + ngspice BSIM4.

The ics55 cell CDL uses `X... / CELL params`; flatten_cdl.py expands those to
transistor devices.  This script converts the flattened M devices to X
instances of the foundry transistor subcircuits, uses a 5 ns transient without
UIC, and measures the DCO period.
"""
from __future__ import annotations

import argparse
import json
import re
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FLATTEN = ROOT / "flow" / "macro" / "ics55_h7cr" / "flatten_cdl.py"
CELL_CDL = Path("/grid/ics55/libs.ref/ics55_LLSC_H7CR/cdl/ics55_LLSC_H7CR.cdl")
MODEL_LIB = Path("/grid/ics55/libs.tech/spice/foundry/ngspice/ICsprout_55LLULP1225_V1p1_hsp.lib")
MODEL_DIR = MODEL_LIB.parent


def read_raw(path: Path):
    b = path.read_bytes()
    marker = b"Binary:\n"
    i = b.index(marker) + len(marker)
    text = b[:i].decode("latin1")
    nv = int(re.search(r"No\. Variables:\s*(\d+)", text).group(1))
    np = int(re.search(r"No\. Points:\s*(\d+)", text).group(1))
    names = re.findall(r"^\s*\d+\s+(\S+)\s+", text, re.M)
    vals = struct.unpack("<%dd" % (nv * np), b[i:i + nv * np * 8])
    time = [vals[k * nv] for k in range(np)]
    traces = {n: [vals[k * nv + j] for k in range(np)] for j, n in enumerate(names)}
    return time, traces


def period_of(time, wave, thresh=0.6):
    edges = [time[k] for k in range(1, len(time)) if wave[k - 1] < thresh <= wave[k]]
    if len(edges) < 3:
        return None
    edges = edges[max(1, int(len(edges) * 0.25)):]
    periods = [b - a for a, b in zip(edges, edges[1:])]
    return sum(periods) / len(periods) if periods else None


def write_code(path: Path, c: int, m: int, f: int):
    s = path.read_text()
    for name, code in (("fine", f), ("mid", m), ("coarse", c)):
        s = re.sub(
            rf"^V{name}<(\d+)> {name}<\d+> GND DC=\S+",
            lambda mm: f"V{name}<{mm.group(1)}> {name}<{mm.group(1)}> GND DC="
                       + ("lvdd" if int(mm.group(1)) < code else "0.0"),
            s, flags=re.M,
        )
    path.write_text(s)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "flow" / "characterization" / "ics55_l3"))
    ap.add_argument("--coarse", default="0,8,15")
    ap.add_argument("--mid", default="0,8,15")
    ap.add_argument("--fine", default="0,8,31")
    ap.add_argument("--stopsim", default="5n")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    # Model library has relative .LIB includes.
    for f in ("model_wrapper1_hsp.lib", "model_wrapper2_hsp.lib"):
        dst = out / f
        if not dst.exists():
            dst.symlink_to(MODEL_DIR / f)
    for d in ("mos", "bjt", "dio", "res", "var", "mom"):
        dst = out / d
        if not dst.exists():
            dst.symlink_to(MODEL_DIR / d, target_is_directory=True)

    # The DCO transistor netlist is generated by syn/Makefile.
    dco = ROOT / "syn" / "outputs" / "ics55" / "PLL_ILDCO.sp"
    if not dco.exists():
        raise SystemExit(f"missing {dco}; run: make -C syn TOP=PLL_ILDCO gen")
    flat = out / "PLL_ILDCO_flat.sp"
    subprocess.run([sys.executable, str(FLATTEN),
                    "--cells", str(CELL_CDL), "--macro", str(dco),
                    "--top", "PLL_ILDCO", "--out", str(flat)],
                   check=True, stdout=subprocess.DEVNULL)
    # Flatten emits M devices; the foundry device wrappers are subcircuits.
    lines = []
    for line in flat.read_text().splitlines():
        if line.startswith("M"):
            toks = line.split()
            toks[0] = "X" + toks[0][1:]
            toks = [("mr=" + t[2:]) if t.startswith("m=") else t for t in toks]
            line = " ".join(toks)
        lines.append(line)
    (out / "PLL_ILDCO_flat_x.sp").write_text("\n".join(lines) + "\n")

    (out / "models_flat.inc").write_text(
        f'.LIB "{MODEL_LIB}" tt_mos\n'
        ".PARAM lvdd=1.2\n"
        ".SUBCKT PLL_CELL_BUFFX0 VDD VSS I Z\n"
        "B1 Z 0 V=V(I)\n"
        ".ENDS\n"
    )
    base = (ROOT / "src" / "test_dco.sp").read_text()
    base = base.replace(".inc models.inc", ".inc models_flat.inc")
    base = base.replace(".inc PLL_ILDCO.sp", ".inc PLL_ILDCO_flat_x.sp")
    base = base.replace(".PARAM stopsim=(10000n)", f".PARAM stopsim=({args.stopsim})")
    (out / "test_dco_l3.sp").write_text(base)
    (out / "test_dco_l3_tran.sp").write_text(
        "* L3 ics55 DCO transient\n"
        ".inc test_dco_l3.sp\n"
        f".tran 1p {args.stopsim}\n"
        ".SAVE V(OUT) V(MID_OUT)\n"
        ".control\nrun\nwrite test_dco_l3.raw\nquit\n.endc\n"
    )

    rows = []
    coarse = [int(x) for x in args.coarse.split(",")]
    mid = [int(x) for x in args.mid.split(",")]
    fine = [int(x) for x in args.fine.split(",")]
    for c in coarse:
        for m in mid:
            for f in fine:
                write_code(out / "test_dco_l3.sp", c, m, f)
                subprocess.run(["ngspice", "-o", "test_dco_l3.log", "test_dco_l3_tran.sp"],
                               cwd=out, check=True, timeout=120,
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                time, traces = read_raw(out / "test_dco_l3.raw")
                p = period_of(time, traces["v(out)"])
                if p is None:
                    print(f"WARN c={c} m={m} f={f}: no edges")
                    continue
                freq = 1e-6 / p
                rows.append({"coarse": c, "mid": m, "fine": f,
                             "period_ns": p / 1e-9, "freq_mhz": freq})
                print(f"c={c:2d} m={m:2d} f={f:2d} period={p*1e9:.3f}ns f={freq:.3f}MHz")

    (out / "dco_tuning_l3.csv").write_text(
        "coarse_code,mid_code,fine_code,period_ns,freq_mhz\n"
        + "\n".join(f"{r['coarse']},{r['mid']},{r['fine']},{r['period_ns']:.6f},{r['freq_mhz']:.6f}" for r in rows)
        + "\n"
    )
    (out / "dco_l3.json").write_text(json.dumps({
        "technology": "ics55",
        "library": "ics55_LLSC_H7CR",
        "model": "BSIM4.5 from ICsprout foundry CDL/model deck",
        "simulator": "ngspice-44.2",
        "characterization_level": "L3_transistor_sparse",
        "points": len(rows),
        "note": "Flattened CDL transistor DCO; no PEX/PVT/jitter signoff.",
        "results": rows,
    }, indent=2) + "\n")
    print(f"wrote {out/'dco_tuning_l3.csv'} ({len(rows)} points)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
